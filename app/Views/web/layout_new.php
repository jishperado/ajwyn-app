$(document).ready(function() {

  // 🔍 Live search
  $('#searchInputBox').on('keyup', function() {

    let query = $(this).val().trim();


    if (query.length < 2) {
      $('.autosearch').hide();
      $('.closeauto').hide();
      return;
    }

    $('.closeauto').show(); // show clear icon

    $.ajax({
      url: "<?= base_url('search/products') ?>",
      method: "GET",
      data: { q: query },
      dataType: "json",

      success: function(response) {
        const products = response.data ?? response;

        if (products && products.length > 0) {

          let html = '<ul class="autoul">';

          products.forEach(product => {

            const imgSrc = product.img 
              ? "<?= base_url('uploads/products/') ?>" + product.img
              : "<?= base_url('web/images/noimage.png') ?>";

            html += `
              <li>
                <a href="<?= base_url('product-details/') ?>${product.id}">
                  <img src="${imgSrc}" alt="${product.product_name}">
                  <span>${product.product_name}</span>
                </a>
              </li>
            `;
          });

          html += "</ul>";

          $('.autoresult').html(html);
          $('.autosearch').show();

        } else {
          $('.autoresult').html('<p style="padding:10px;color:#777;">No products found</p>');
          $('.autosearch').show();
        }
      },

      error: function() {
        $('.autoresult').html('<p style="padding:10px;color:#777;">Error loading results</p>');
        $('.autosearch').show();
      }
    });

  });

  $('.closeauto').click(function() {
    $('#searchInputBox').val('');
    $('.autosearch').hide();
    $(this).hide();
  });
  $(document).click(function(e) {
    if (!$(e.target).closest('.autosearch, #searchInputBox').length) {
      $('.autosearch').hide();
    }
  });


  $('#searchInputBox').on('keypress', function(e) {
    if (e.which == 13 && $('.autoresult a').length > 0) {
      e.preventDefault();
      window.location.href = $('.autoresult a').first().attr('href');
    }
  });

});
</script>
	
